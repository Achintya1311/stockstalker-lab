"""Write the COMPOSITE_V2 config modules, their catalog rows and their held train replays from one table.

The table is `strategies.composite_v2.CONFIGS` (per horizon, every setting on every table where it exists).
For each config this writes one thin module, `strategies/composite_v2_<table>_<setting>.py`. With `--queue`
it also appends any missing `cards/catalog.csv` row and writes one train replay yml per config into
`experiments/held/v2/` (never `experiments/pending/`):

    week/    every week config
    day_a/   the first half of the day configs in declared order: families A (vote) and B (boost) first,
             whole config keys only, so both tables of a key land in the same folder
    day_b/   the rest of the day configs

A yml is never written when its experiment id already exists in `experiments/pending/`, any folder under
`experiments/held/`, or `experiments/done/`. `--check` verifies that every module on disk matches the table
and that no stale `composite_v2_*` module is left (used by `tests/test_composite_v2.py`).

    python3 -m scripts.gen_composite_v2              # modules only
    python3 -m scripts.gen_composite_v2 --queue      # modules, catalog rows, held replays
    python3 -m scripts.gen_composite_v2 --check
"""

from __future__ import annotations

import argparse
import csv
import io
import sys
from pathlib import Path

from strategies import composite_v2 as C
from strategies.g_gates import TRIGGERS

ROOT = Path(__file__).resolve().parent.parent
STRATEGIES = ROOT / "strategies"
EXPERIMENTS = ROOT / "experiments"
HELD_V2 = EXPERIMENTS / "held" / "v2"
CATALOG = ROOT / "cards" / "catalog.csv"
TRAIN = ("2015-01-01", "2020-12-31")  # config/splits.yml train
PREFIX = "composite_v2_"


def module_name(table: str, setting_key: str) -> str:
    return f"{PREFIX}{table}_{setting_key}"


def experiment_id(table: str, setting_key: str) -> str:
    return module_name(table, setting_key).replace("_", "-") + f"-{C.horizon_of(table)}"


def ordered_configs() -> list[tuple[str, str]]:
    """Configs in declared order: horizon, then setting (A, B, C as declared), then bullish before bearish."""
    out = []
    for horizon, settings in C.SETTINGS.items():
        for s in settings:
            for table in C.HORIZON_TABLES[horizon]:
                if (table, s.key) in C.CONFIGS:
                    out.append((table, s.key))
    return out


def folders() -> dict[tuple[str, str], str]:
    """(table, setting_key) -> held folder name."""
    out = {}
    day = [c for c in ordered_configs() if C.horizon_of(c[0]) == "day"]
    half = len(day) // 2
    placed, full = 0, False
    for key in dict.fromkeys(k for _, k in day):  # whole keys, declared order
        pair = [c for c in day if c[1] == key]
        full = full or placed + len(pair) > half
        folder = "day_b" if full else "day_a"
        if not full:
            placed += len(pair)
        for c in pair:
            out[c] = folder
    for c in ordered_configs():
        if C.horizon_of(c[0]) == "week":
            out[c] = "week"
    return out


def module_text(table: str, setting_key: str) -> str:
    s = C.CONFIGS[(table, setting_key)]
    t = TRIGGERS[C.TABLES[table]]
    return (
        f'"""{C.config_id(table, setting_key)}: {t.label} {t.side_word} picks, {C.describe(table, s)}.\n\n'
        f"COMPOSITE_V2 family {s.family_letter} ({s.family}), config key {C.config_key(table, s)} "
        f"(`cards/COMPOSITE_V2.yml`); rules in `strategies/composite_v2.py`.\n"
        f"Compare with {t.label} alone. Generated by `scripts/gen_composite_v2.py`; do not edit.\n"
        '"""\n\n'
        "from strategies.composite_v2 import config\n\n"
        f'score, rules_fired = config("{table}", "{setting_key}")\n'
    )


def experiment_text(table: str, setting_key: str) -> str:
    return (
        f"id: {experiment_id(table, setting_key)}\n"
        f"strategy: strategies.{module_name(table, setting_key)}\n"
        "split: train\n"
        f"horizon: {C.horizon_of(table)}\n"
        f"dates: {{start: '{TRAIN[0]}', end: '{TRAIN[1]}'}}\n"
    )


def catalog_row(table: str, setting_key: str) -> list[str]:
    s = C.CONFIGS[(table, setting_key)]
    t = TRIGGERS[C.TABLES[table]]
    key = C.config_key(table, s)
    keep_rule = (
        "every pick kept, ranked by the trigger score times the gate-count factor"
        if s.family == "boost" else "a subset of the trigger's picks with its scores unchanged"
    )
    return [
        C.config_id(table, setting_key),
        f"{t.label} {t.side_word} picks, {s.key} (composite v2)",
        "confluence",
        t.horizon,
        f"{t.label} {t.side_word} picks, {C.describe(table, s)}; {keep_rule}. Family {s.family_letter}, config key "
        f"{key}, built on both tables of the {t.horizon} horizon where the gate exists. Rules in strategies/composite_v2.py. "
        f"Judged on train only by the selection pre-declared in cards/COMPOSITE_V2.yml (fit years 2015-2018, inner check "
        f"2019 and 2020, at least 40% of {t.label}'s dates).",
        f"as {t.label}; " + (", ".join(f"{k}={v:g}" for k, v in C.gate_kwargs(table, s).items()) if s.family == "threshold"
                             else f"{'k' if s.family == 'vote' else 'w'}={s.value:g}; gate thresholds as C1"),
        "ohlcv plus futures OI",
        "yes",
        "cards/COMPOSITE_V2.yml; research/diagnostics/composite_ingredients.md; research/diagnostics/composite_v1.md",
        "",
        f"Does {key} beat {t.label} alone on the {t.horizon} {t.side_word} table, and on the other side too",
        "held",
    ]


def write_modules(check: bool) -> list[str]:
    stale = []
    wanted = set()
    for table, key in C.CONFIGS:
        path = STRATEGIES / f"{module_name(table, key)}.py"
        wanted.add(path.name)
        text = module_text(table, key)
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    for path in STRATEGIES.glob(f"{PREFIX}*.py"):
        if path.name not in wanted and not path.stem.endswith("_audit"):
            stale.append(f"{path.relative_to(ROOT)} (not a config)")
    return stale


def already_queued(exp_id: str, experiments: Path = EXPERIMENTS) -> bool:
    held = experiments / "held"
    return (
        (experiments / "pending" / f"{exp_id}.yml").exists()
        or (held.is_dir() and any(held.rglob(f"{exp_id}.yml")))
        or (experiments / "done" / exp_id).exists()
    )


def queue(experiments: Path = EXPERIMENTS, catalog: Path = CATALOG) -> list[str]:
    written = []
    for (table, key), folder in folders().items():
        exp_id = experiment_id(table, key)
        if already_queued(exp_id, experiments):
            continue
        dest = experiments / "held" / "v2" / folder
        dest.mkdir(parents=True, exist_ok=True)
        (dest / f"{exp_id}.yml").write_text(experiment_text(table, key))
        written.append(str((dest / f"{exp_id}.yml").relative_to(experiments.parent)))
    existing = {row[0] for row in csv.reader(catalog.read_text().splitlines()) if row}
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\r\n")  # the catalog uses CRLF line ends
    for table, key in ordered_configs():
        row = catalog_row(table, key)
        if row[0] not in existing:
            writer.writerow(row)
    if buf.getvalue():
        text = catalog.read_bytes().decode()
        catalog.write_bytes((text + ("" if text.endswith("\n") else "\r\n") + buf.getvalue()).encode())
    return written


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--queue", action="store_true")
    args = ap.parse_args(argv)
    stale = write_modules(args.check)
    if args.check:
        for s in stale:
            print(f"out of sync: {s}")
        return 1 if stale else 0
    written = queue() if args.queue else []
    for w in written:
        print(f"held {w}")
    print(f"{len(C.CONFIGS)} configs" + (f", {len(written)} replays held" if args.queue else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
